import { ApiProperty } from '@nestjs/swagger';

export class HistoryReadingsSummaryDto {
  @ApiProperty({ example: 12, description: 'Total readings generated by the user' })
  total!: number;

  @ApiProperty({ example: 2, description: 'Readings still pending evaluation' })
  pending!: number;

  @ApiProperty({ example: 10, description: 'Readings already evaluated' })
  completed!: number;

  @ApiProperty({ example: 7, description: 'Completed readings with a passing score' })
  passed!: number;

  @ApiProperty({
    example: 83,
    nullable: true,
    description: 'Average score across completed readings, or null when none exist',
  })
  averageScore!: number | null;
}

export class HistoryScoreEntryDto {
  @ApiProperty({ example: 42 })
  readingId!: number;

  @ApiProperty({ example: 'The rise of steam power' })
  title!: string;

  @ApiProperty({ example: 85, nullable: true })
  score!: number | null;

  @ApiProperty({ example: true, nullable: true })
  passed!: boolean | null;

  @ApiProperty({ example: '2026-10-18T00:00:00.000Z', nullable: true })
  evaluatedAt!: Date | null;
}

export class HistorySummaryDto {
  @ApiProperty({ type: HistoryReadingsSummaryDto })
  readings!: HistoryReadingsSummaryDto;

  @ApiProperty({
    type: [HistoryScoreEntryDto],
    description: 'Latest completed readings with their score, newest first',
  })
  recentScores!: HistoryScoreEntryDto[];

  @ApiProperty({
    example: 0,
    description:
      'Words looked up by the user. Returns 0 until the lookup-persistence table lands (see follow-up issue).',
  })
  wordsLookedUp!: number;
}
